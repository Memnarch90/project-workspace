const schema=readFileSync(new URL('../schema.sql',import.meta.url),'utf8');
test('Project name and description edits are owner-scoped, versioned and audited once',async t=>{
 const db=sqliteAdapter(':memory:');db.exec(schema);t.after(()=>db.close());
 const service=workspace(db,'owner'),write=(kind,input,operationId)=>service.write(kind,input,operationId,'connector:qa');
 const {record:project}=await write('create_project',{name:'Example project',description:'Original'},'project-desc-create');
 const input={project_id:project.id,expected_version:1,changes:{description:'Revised'}};
 await assert.rejects(workspace(db,'another-owner').write('update_project',input,'project-desc-denied','test'),/Project not found/);
 await assert.rejects(write('update_project',{...input,changes:{status:'Parked'}},'project-unsupported-status'),/Unsupported project status/);
 await assert.rejects(write('update_project',{...input,changes:{archived:true}},'project-unsupported-field'),/name, description, status or information/);
 await assert.rejects(write('update_project',{...input,changes:{name:'  '}},'project-blank-name'),/Invalid project name/);
 const [first,retry]=await Promise.all([write('update_project',input,'project-desc-update'),write('update_project',input,'project-desc-update')]);
 assert.deepEqual(first,retry);
 assert.deepEqual(first.record,{...project,description:'Revised',version:2});
 await assert.rejects(write('update_project',{...input,changes:{description:'Another'}},'project-desc-update'),/different changes/);
 await assert.rejects(write('update_project',input,'project-desc-stale'),/Conflict/);
 const audit=(await db.prepare("SELECT * FROM audit_events WHERE action='update_project'").all()).results;
 assert.equal(audit.length,1);
 assert.equal(audit[0].entity_type,'project');
 assert.equal(audit[0].actor,'connector:qa');
 assert.equal(JSON.parse(audit[0].before_json).description,'Original');
 assert.equal(JSON.parse(audit[0].after_json).description,'Revised');
 await write('create_project',{name:'Other project'},'project-duplicate-target');
 await assert.rejects(write('update_project',{...input,expected_version:2,changes:{name:'Other project'}},'project-duplicate-name'),/already exists/);
 const rename=await write('update_project',{...input,expected_version:2,changes:{name:'Renamed project'}},'project-rename');
 assert.deepEqual(rename.record,{...project,name:'Renamed project',description:'Revised',version:3});
 await write('update_project',{...input,expected_version:3,changes:{description:''}},'project-desc-clear');
 const cleared=(await service.projects()).find(item=>item.id===project.id);
 assert.equal(cleared.name,'Renamed project');
 assert.equal(cleared.description,'');
});
test('workspace: transactions, retries, isolation, milestones, dependency cycles and completion',async()=>{
 const db=sqliteAdapter(':memory:');db.exec(schema);const service=workspace(db,'owner');
 try{
  const p=(await service.write('create_project',{name:'Example project'},'project-0001','test')).record;
  const input={changes:{title:'Example task',project_id:p.id,notes:'Keep the original note.',due_date:'2026-12-01'}};
  const first=await service.write('create_task',input,'create-task-0001','test');
  assert.deepEqual(await service.write('create_task',input,'create-task-0001','test'),first);
  await assert.rejects(()=>service.write('create_task',{changes:{...input.changes,title:'Different'}},'create-task-0001','test'),/different/);
  let task=await service.getTask(first.record.id);assert.equal(task.version,1);
  assert.equal(task.assignee,'Unassigned');
  const complete=await service.write('update_task',{task_id:task.id,expected_version:1,changes:{done:true}},'complete-0001','test');
  assert.equal(complete.record.done,true);assert.equal(complete.record.action_status,'Completed');assert.ok(complete.record.completed_on);
  await assert.rejects(()=>service.write('update_task',{task_id:task.id,expected_version:1,changes:{notes:'Overwrite'}},'stale-update-0001','test'),/Conflict/);
  task=await service.getTask(task.id);assert.equal(task.notes,'Keep the original note.');
  const reopened=await service.write('update_task',{task_id:task.id,expected_version:2,changes:{done:false}},'reopen-task-0001','test');
  assert.equal(reopened.record.completed_on,null);assert.equal(reopened.record.action_status,'Not Started');
  const milestone=(await service.write('create_task',{changes:{title:'Example milestone',project_id:p.id,item_type:'Milestone'}},'milestone-0001','test')).record;
  const linked=await service.write('update_task',{task_id:task.id,expected_version:3,changes:{milestone_id:milestone.id}},'link-milestone-0001','test');assert.equal(linked.record.milestone_id,milestone.id);
  await service.write('link_dependency',{task_id:task.id,prerequisite_id:milestone.id},'dependency-0001','test');
  await assert.rejects(()=>service.write('link_dependency',{task_id:milestone.id,prerequisite_id:task.id},'cycle-0001','test'),/cycle/);
  // The database also rejects a cycle independently of the preflight check.
  await assert.rejects(()=>db.prepare('INSERT INTO dependencies VALUES(?1,?2)').bind(milestone.id,task.id).run(),/cycle/);
  assert.equal((await service.findTasks({view:'next'})).tasks.some(t=>t.id===task.id),false);
  await service.write('update_task',{task_id:milestone.id,expected_version:1,changes:{done:true}},'complete-milestone-0001','test');
  assert.equal((await service.findTasks({view:'next'})).tasks.some(t=>t.id===task.id),true);
  assert.equal((await service.summary()).tasks,2);assert.equal((await service.summary()).milestones,1);
  await assert.rejects(()=>workspace(db,'intruder').getTask(task.id),/not found/);
  assert.deepEqual(await workspace(db,'intruder').projects(),[]);
  await assert.rejects(()=>workspace(db,'intruder').write('create_task',{changes:{title:'Cross-owner',project_id:p.id}},'cross-owner-0001','test'),/not found/);
  await assert.rejects(()=>service.write('update_task',{task_id:task.id,expected_version:4,changes:{version:999}},'protected-0001','test'),/cannot be changed/);
  await assert.rejects(()=>service.write('create_task',{changes:{title:'Bad date',due_date:'2026-02-30'}},'bad-date-0001','test'),/YYYY-MM-DD/);
  const changes=await service.changes(0,2);assert.equal(changes.changes.length,2);assert.equal(changes.has_more,true);
  assert.ok((await service.audit(task.id)).some(e=>e.action==='update_task'));
  const historic=(await service.write('create_task',{changes:{title:'Historical completed item',done:true}},'historic-task-0001','test')).record;
  await db.prepare('UPDATE tasks SET completed_on=NULL WHERE id=?1').bind(historic.id).run();
  const stillUnknown=await service.write('update_task',{task_id:historic.id,expected_version:1,changes:{done:true}},'historic-repeat-0001','test');
  assert.equal(stillUnknown.record.completed_on,null,'Already-completed imports with unknown dates must remain unknown.');
  await assert.rejects(()=>service.write('update_task',{task_id:milestone.id,expected_version:2,changes:{item_type:'Task'}},'invalid-milestone-0001','test'),/Other tasks/);
  await service.write('unlink_dependency',{task_id:task.id,prerequisite_id:milestone.id},'unlink-dependency-0001','test');
  assert.deepEqual((await service.getTask(task.id)).dependencies,[]);
  const focusWrite=await service.write('set_focus',{task_id:task.id,selected:true},'my-day-focus-0001','test');
  assert.equal(focusWrite.record.selected,true);
  assert.deepEqual(await workspace(db,'owner').focus(),await service.focus());
  assert.ok((await service.focus()).includes(task.id));
  assert.deepEqual(await workspace(db,'intruder').focus(),[]);
  await assert.rejects(()=>workspace(db,'intruder').write('set_focus',{task_id:task.id,selected:true},'intruder-focus-0001','test'),/not found/);
  await service.write('set_focus',{task_id:task.id,selected:false},'my-day-remove-0001','test');
  assert.ok(!(await service.focus()).includes(task.id));
  assert.ok((await service.exportPlan(p.id)).every(t=>t.project_id===p.id));
  assert.deepEqual(await workspace(db,'intruder').exportPlan(p.id),[]);
 }finally{db.close();}
});
